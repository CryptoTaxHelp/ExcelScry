#!/usr/bin/env python3
"""Check the updater signing key before a release or installer spends minutes building.

`createUpdaterArtifacts` is on, so every `tauri build` signs its installer, and
the release job goes on to sign `latest.json` with the same key. Without
`TAURI_SIGNING_PRIVATE_KEY` the build fails - after compiling the whole app - as
an exit 1 from `tauri build` that says nothing about a secret. A workflow cannot
test a secret in a step's `if:`, so the check is a step of its own that reads the
environment and fails on its first line.

Being present is not the same as being the right key. A secret holding another
key's material builds and signs perfectly well, and the failure surfaces after
the build, in the published manifest's verification, as an app that would refuse
every update this release offers. So the key is read the way the Tauri CLI reads
it - base64 of a minisign secret key file - and its key id and public key are
held against the `pubkey` committed in `tauri.conf.json`. A key from `tauri
signer generate` is encrypted even when it has no password, so the material is
decrypted with `TAURI_SIGNING_PRIVATE_KEY_PASSWORD` - empty when that secret is
unset, which is what the CLI assumes when it is not given one - to identify it.

    python scripts/verify_signing_key.py

Reads `TAURI_SIGNING_PRIVATE_KEY` and `TAURI_SIGNING_PRIVATE_KEY_PASSWORD` from
the environment, and never prints either. The key may be the base64 of a key
file or a path to one, which is what `release.py` passes when it runs this
check on a developer's machine. Exit status 1 means this build cannot be
signed, and says what to do about it.
"""

from __future__ import annotations

import base64
import binascii
import dataclasses
import hashlib
import os
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import verify_release

# What a minisign secret key file is: an untrusted comment line, then base64 of
# the key. `minisign-0.9`'s SecretKey::from_bytes reads, in order: the signature
# algorithm, the KDF algorithm, the checksum algorithm, a KDF salt, the KDF
# limits, the key id, the 64-byte Ed25519 secret and a BLAKE2b checksum over the
# first, key id and secret.
SIG_ALGORITHM = 2
KDF_SALT = 32
KDF_LIMIT = 8
KEY_ID = 8
SECRET = 64
CHECKSUM = 32
SECRET_KEY_LENGTH = (
    SIG_ALGORITHM * 3 + KDF_SALT + KDF_LIMIT * 2 + KEY_ID + SECRET + CHECKSUM
)
ED25519 = b"Ed"
KDF_NONE = b"\x00\x00"

KEY_ENV = "TAURI_SIGNING_PRIVATE_KEY"
PASSWORD_ENV = "TAURI_SIGNING_PRIVATE_KEY_PASSWORD"


@dataclasses.dataclass
class SigningKey:
    """What the secret's material says about itself."""

    key_id: bytes
    public_key: bytes
    encrypted: bool


# What `minisign` accepts from a key's stored KDF limits.
N_LOG2_MAX = 20
MEMLIMIT_MAX = 1_073_741_824


def scrypt_parameters(memlimit: int, opslimit: int) -> tuple[int, int, int]:
    """The scrypt cost `minisign` derives from a key's stored limits.

    Mirrors `minisign`'s `raw_scrypt_params`, so the stream below is the one the
    key was encrypted with rather than a guess at it.
    """
    opslimit = max(32768, opslimit)
    r = 8
    n_log2 = 1
    if opslimit < memlimit // 32:
        p = 1
        maxn = opslimit // (r * 4)
        while n_log2 < 63 and (1 << n_log2) <= maxn // 2:
            n_log2 += 1
    else:
        maxn = memlimit // (r * 128)
        while n_log2 < 63 and (1 << n_log2) <= maxn // 2:
            n_log2 += 1
        maxrp = min(0x3FFF_FFFF, (opslimit // 4) // (1 << n_log2))
        p = maxrp // r

    if n_log2 > N_LOG2_MAX:
        raise SystemExit(
            f"error: the updater signing key asks for an scrypt cost of 2^{n_log2},\n"
            f"       beyond the 2^{N_LOG2_MAX} `minisign` allows, so it cannot be\n"
            "       decrypted here or by `tauri signer sign`."
        )
    return n_log2, r, p


def decrypt(blob: bytes, password: str) -> tuple[bytes, bytes, bytes]:
    """The key id, secret and checksum inside an encrypted secret key.

    A key generated by `tauri signer generate` is encrypted even when no
    password is given, so this is the normal case rather than the exception:
    the key material is xor'd with an scrypt stream over the password, and the
    CLI assumes an empty password when it is not given one.
    """
    # The stored key, in the order `SecretKey::from_bytes` reads it.
    salt_start = SIG_ALGORITHM * 3
    ops_start = salt_start + KDF_SALT
    limits_start = ops_start + KDF_LIMIT
    salt = blob[salt_start:ops_start]
    opslimit = int.from_bytes(blob[ops_start:limits_start], "little")
    memlimit = int.from_bytes(blob[limits_start : limits_start + KDF_LIMIT], "little")
    if memlimit > MEMLIMIT_MAX:
        raise SystemExit(
            "error: the updater signing key asks for more memory than `minisign`\n"
            f"       allows ({memlimit} bytes), so it cannot be decrypted here or\n"
            "       by `tauri signer sign`."
        )
    n_log2, r, p = scrypt_parameters(memlimit, opslimit)

    stream = hashlib.scrypt(
        password.encode("utf-8"),
        salt=salt,
        n=1 << n_log2,
        r=r,
        p=p,
        maxmem=max(memlimit, 128 * (1 << n_log2) * r) + (1 << 20),
        dklen=KEY_ID + SECRET + CHECKSUM,
    )

    start = limits_start + KDF_LIMIT

    def unmask(offset: int, length: int) -> bytes:
        masked = blob[offset : offset + length]
        return bytes(byte ^ mask for byte, mask in zip(masked, stream[offset - start :]))

    return (
        unmask(start, KEY_ID),
        unmask(start + KEY_ID, SECRET),
        unmask(start + KEY_ID + SECRET, CHECKSUM),
    )


def _base64(value: str, what: str) -> bytes:
    try:
        return base64.b64decode(value.strip(), validate=True)
    except (binascii.Error, ValueError):
        raise SystemExit(
            f"error: {what} is not valid base64.\n"
            "       The secret is the base64 of a key file, which is what\n"
            "       `base64 -w0 < ~/.tauri/ExcelScry.key` writes on Linux or\n"
            "       `[Convert]::ToBase64String([IO.File]::ReadAllBytes(...))` on\n"
            "       Windows, or a path to the key file such as\n"
            "       ~/.tauri/ExcelScry.key; pasting the key file itself fails here."
        ) from None


def key_from_secret(secret: str, password: str = "") -> SigningKey:
    """Read a minisign secret key the way the Tauri CLI does.

    Never returns the secret material: only the key id and public key it
    carries, which are what a signing key is identified by.
    """
    if not secret.strip():
        raise SystemExit(
            f"error: {KEY_ENV} is empty, so this build cannot be signed.\n"
            "       Every `tauri build` signs its updater artifact, so a build\n"
            "       without the key fails minutes later as an exit 1 from\n"
            "       `tauri build` that says nothing about a secret. Locally, set\n"
            "       it to the key file, or put the key at ~/.tauri/ExcelScry.key:\n"
            "\n"
            "         export TAURI_SIGNING_PRIVATE_KEY=~/.tauri/ExcelScry.key\n"
            "\n"
            "       In CI, add it to this repository's Actions secrets:\n"
            "\n"
            "         gh secret set TAURI_SIGNING_PRIVATE_KEY < ~/.tauri/ExcelScry.key\n"
            "\n"
            "       ...where the file holds the base64 secret key as it is written\n"
            "       there. A path to the file is accepted here as well."
        )

    # `release.py` has the developer's key as a file, so accept a path as well
    # as the base64 secret CI passes. A pasted key file has newlines and is left
    # for `_base64` to refuse, rather than being probed as a filename.
    #
    # The file may hold the key itself, or the base64 of it - which is what
    # `tauri signer generate` prints and what a developer pastes into the
    # secret, so it is a common way to keep one on disk. The CLI reads such a
    # file's content and decodes it, which is why both work there; so does this.
    candidate = secret.strip()
    text = None
    if "\n" not in candidate and pathlib.Path(candidate).is_file():
        content = pathlib.Path(candidate).read_text(encoding="utf-8", errors="replace")
        if content.lstrip().startswith("untrusted comment:"):
            text = content
        else:
            secret = content.strip()
    if text is None:
        text = _base64(secret, f"{KEY_ENV}").decode("utf-8", "replace")
    lines = [line for line in text.splitlines() if line.strip()]
    if len(lines) < 2 or not lines[0].startswith("untrusted comment:"):
        raise SystemExit(
            f"error: {KEY_ENV} does not decode to a minisign secret key: its\n"
            "       first line is not an untrusted comment."
        )

    blob = _base64(lines[1], "the minisign secret key")
    if len(blob) != SECRET_KEY_LENGTH:
        raise SystemExit(
            f"error: the minisign secret key in {KEY_ENV} is {len(blob)} bytes,\n"
            f"       not {SECRET_KEY_LENGTH}. The secret is truncated or is not a\n"
            "       minisign secret key at all."
        )
    if blob[:2] != ED25519:
        raise SystemExit(
            f"error: the key in {KEY_ENV} is not Ed25519 ({blob[:2]!r}), and the\n"
            "       updater only verifies Ed25519 minisign signatures."
        )

    encrypted = blob[2:4] != KDF_NONE
    if encrypted:
        key_id, secret_key, checksum = decrypt(blob, password)
    else:
        start = SIG_ALGORITHM * 3 + KDF_SALT + KDF_LIMIT * 2
        key_id = blob[start : start + KEY_ID]
        secret_key = blob[start + KEY_ID : start + KEY_ID + SECRET]
        checksum = blob[start + KEY_ID + SECRET :]

    # `minisign` refuses a secret whose checksum does not cover its key id and
    # secret, which is what catches a key damaged in transit to the secret, and
    # what says a password was wrong when the key is encrypted.
    expected = hashlib.blake2b(
        blob[:2] + key_id + secret_key, digest_size=CHECKSUM
    ).digest()
    if checksum != expected:
        if encrypted:
            raise SystemExit(
                "error: the updater signing key could not be decrypted with\n"
                f"       {PASSWORD_ENV} (which is empty when that secret is\n"
                "       unset). That is either the wrong password or a damaged\n"
                "       key; `tauri signer sign` would fail the same way, but only\n"
                "       after the build."
            )
        raise SystemExit(
            f"error: the minisign secret key in {KEY_ENV} fails its own checksum.\n"
            "       The key material was altered - a partial paste, or a key file\n"
            "       that was edited - and `tauri signer sign` would refuse it.\n"
            "       Set the secret from the key file again."
        )
    return SigningKey(
        key_id=key_id,
        public_key=secret_key[SECRET // 2 :],
        encrypted=encrypted,
    )


def check_against_pubkey(key: SigningKey, pubkey: str) -> None:
    """Hold the secret's key to the one an installed copy will trust."""
    trusted_id, trusted_key = verify_release.minisign_public_key(pubkey)
    if key.key_id != trusted_id:
        raise SystemExit(
            "error: the signing key is not the one this build trusts.\n"
            f"       {KEY_ENV} holds key id {key.key_id.hex()}, but\n"
            f"       tauri.conf.json's pubkey is {trusted_id.hex()}.\n"
            "       A release built with it would sign everything correctly and be\n"
            "       refused by every installed copy, which trusts the key in\n"
            "       tauri.conf.json. Either set the secret to the matching key, or\n"
            "       roll the key over as described under 'The signing key' in\n"
            "       README.md."
        )
    if key.public_key != trusted_key:
        raise SystemExit(
            "error: the signing key carries the same key id as the one this build\n"
            "       trusts, but different key material. Signatures it makes would be\n"
            "       refused, and a key id that matches another key's is not something\n"
            "       minisign produces: the secret is damaged."
        )


def main() -> int:
    config = verify_release.read_config()
    pubkey = config.get("plugins", {}).get("updater", {}).get("pubkey")
    if not pubkey:
        raise SystemExit(
            "error: tauri.conf.json has no updater pubkey, so there is no key this\n"
            "       release would have to be signed with."
        )

    key = key_from_secret(
        os.environ.get(KEY_ENV, ""), os.environ.get(PASSWORD_ENV, "")
    )
    check_against_pubkey(key, pubkey)
    print("The updater signing key is present, and is the one this build trusts.")
    print(f"  key        {key.key_id.hex()}")
    if key.encrypted:
        print("  encrypted  decrypted with the password secret to identify it")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
